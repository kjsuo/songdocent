export function reasoningLabel(level: string, copy: (typeof aiCopy)[LangCode]): string {
  switch (level) {
    case "none": return copy.reasoning_none;
    case "minimal": return copy.reasoning_minimal;
    case "low": return copy.reasoning_low;
    case "medium": return copy.reasoning_medium;
    case "high": return copy.reasoning_high;
    case "xhigh": return copy.reasoning_xhigh;
    case "max": return copy.reasoning_max;
    case "ultra": return copy.reasoning_ultra;
    default: return level;
  }
}
